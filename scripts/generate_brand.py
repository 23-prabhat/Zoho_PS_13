#!/usr/bin/env python3
"""Export Shikai's original vector mark; PNG exports use the report environment's Pillow."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / 'assets/brand'


def points(value):
    return ' '.join(f'{x},{y}' for x, y in value)


def svg(mark, first, second):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -4 144 136" role="img" aria-label="Shikai folded S logo">'
        '<title>Shikai — The Fold</title><defs><mask id="opening"><rect x="-8" y="-4" width="144" height="136" fill="white"/>'
        f'<polygon points="{points(mark["aperture"])}" fill="black"/></mask></defs><g mask="url(#opening)">'
        f'<polygon points="{points(mark["upper"])}" fill="{first}"/>'
        f'<polygon points="{points(mark["lower"])}" fill="{second}"/></g>'
        f'<polygon points="{points(mark["core"])}" fill="{second}"/></svg>\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--png', action='store_true', help='Also export transparent PNGs (requires Pillow)')
    args = parser.parse_args()
    mark = json.loads((BRAND/'shikai-mark.json').read_text())
    c = mark['colors']
    variants = {'shikai-mark': (c['teal'], c['copper']), 'shikai-mark-mono': (c['ink'], c['ink']),
                'shikai-mark-reversed': (c['reverse_teal'], c['reverse_copper'])}
    for name, (first, second) in variants.items():
        (BRAND/(name+'.svg')).write_text(svg(mark, first, second))
        if args.png:
            from PIL import Image, ImageDraw
            size = 2048
            scale = size/144
            im = Image.new('RGBA', (size, round(136*scale)), (0, 0, 0, 0))
            d = ImageDraw.Draw(im)
            xy = lambda field: [((x+8)*scale, (y+4)*scale) for x,y in mark[field]]
            d.polygon(xy('upper'), fill=first); d.polygon(xy('lower'), fill=second)
            d.polygon(xy('aperture'), fill=(0,0,0,0)); d.polygon(xy('core'), fill=second)
            im.save(BRAND/(name+'.png'))
            im.resize((512,round(136*512/144)),Image.Resampling.LANCZOS).save(BRAND/(name+'-512.png'))
    (BRAND/'shikai-ascii.txt').write_text('\n'.join(mark['ascii'])+'\n')
    lines = ',\n'.join('    '+json.dumps(line) for line in mark['ascii'])
    header = ('// Generated by scripts/generate_brand.py from assets/brand/shikai-mark.json.\n'
        '#pragma once\n#include <array>\n#include <string_view>\nnamespace local_llm::brand {\n'
        'inline constexpr std::array<std::string_view, '+str(len(mark['ascii']))+'> mark{\n'+lines+'\n};\n}\n')
    (ROOT/'include/local_llm/brand.hpp').write_text(header)
    print('Exported Shikai vector/terminal assets'+(' and transparent PNGs.' if args.png else '.'))


if __name__ == '__main__':
    main()
